"""Cities, barrios and how each site names them.

Every site names locations differently: MercadoLibre has "Palermo Soho" as a
place of its own, CabaProp splits Barrio Norte into four zones, ArgenProp
files cards under numeric ids. And "Barrio Norte" is not an official CABA
barrio at all. We therefore never match on the address string; we map the
*structured* location value each site gives us (URL path, location field or
internal id) onto a canonical (city, barrio) through one table.

The table lives in monitor/data/locations.json, generated by
scripts/build_locations.py. NEIGHBORHOOD_MAP_FILE can point at a replacement
with the same shape:

    {"cities": {"CABA": {"aliases": [...], "slugs": {source: [...]},
                         "ids": {source: [...]},
                         "barrios": {"Recoleta": {"aliases": [...],
                                                  "slugs": {source: [...]},
                                                  "ids": {source: [...]}}}}}}

Barrio names repeat between cities ("Centro", "Belgrano"), so a barrio is
always qualified by its city.
"""

from __future__ import annotations

import json
import os
import re
import unicodedata
from dataclasses import dataclass
from typing import Any, Dict, Iterable, List, Optional

DEFAULT_LOCATIONS_FILE = os.path.join(os.path.dirname(__file__), "data", "locations.json")
KEY_SEPARATOR = "/"


def normalize_text(value: str) -> str:
    """Lowercase, strip accents and collapse separators."""
    decomposed = unicodedata.normalize("NFKD", value)
    without_accents = "".join(c for c in decomposed if not unicodedata.combining(c))
    cleaned = re.sub(r"[^a-z0-9]+", " ", without_accents.lower())
    return cleaned.strip()


@dataclass(frozen=True)
class Location:
    city: str
    neighborhood: Optional[str] = None


def barrio_key(city: str, barrio: str) -> str:
    """How a search stores a barrio: "CABA/Recoleta"."""
    return f"{city}{KEY_SEPARATOR}{barrio}"


def split_key(key: str, default_city: str = "CABA") -> Location:
    """The inverse of barrio_key. A bare name is a CABA barrio: that is how
    searches were stored before cities existed."""
    if KEY_SEPARATOR in key:
        city, barrio = key.split(KEY_SEPARATOR, 1)
        return Location(city, barrio)
    return Location(default_city, key)


def _load(path: Optional[str]) -> Dict[str, Any]:
    with open(path or DEFAULT_LOCATIONS_FILE, encoding="utf-8") as handle:
        data = json.load(handle)
    return data.get("cities", data)


class NeighborhoodResolver:
    def __init__(self, cities: Optional[Dict[str, Any]] = None) -> None:
        self.cities_map: Dict[str, Any] = cities if cities is not None else _load(None)
        self._city_aliases: Dict[str, str] = {}
        # A label can name barrios in several cities ("Centro").
        self._labels: Dict[str, List[Location]] = {}
        self._slugs: Dict[str, Location] = {}
        self._ids: Dict[str, Location] = {}

        for city, spec in self.cities_map.items():
            self._city_aliases[normalize_text(city)] = city
            for alias in spec.get("aliases") or []:
                self._city_aliases[normalize_text(alias)] = city
            self._index(Location(city), spec, labels=False)
            for barrio, barrio_spec in (spec.get("barrios") or {}).items():
                location = Location(city, barrio)
                for label in [barrio, *(barrio_spec.get("aliases") or [])]:
                    found = self._labels.setdefault(normalize_text(label), [])
                    if location not in found:
                        found.append(location)
                self._index(location, barrio_spec, labels=True)

    def _index(self, location: Location, spec: Dict[str, Any], labels: bool) -> None:
        for source, slugs in (spec.get("slugs") or {}).items():
            for slug in slugs:
                self._slugs[f"{source}|{slug.strip('/')}"] = location
        for source, ids in (spec.get("ids") or {}).items():
            for identifier in ids:
                self._ids[f"{source}|{str(identifier).strip()}"] = location

    @classmethod
    def from_file(cls, path: Optional[str]) -> NeighborhoodResolver:
        return cls(_load(path))

    # ------------------------------------------------------------------ catalog

    def cities(self) -> List[str]:
        return list(self.cities_map.keys())

    def neighborhoods(self, city: str) -> List[str]:
        return list((self.cities_map.get(city) or {}).get("barrios") or {})

    def _spec(self, city: str, barrio: Optional[str] = None) -> Dict[str, Any]:
        spec = self.cities_map.get(city) or {}
        if barrio is not None:
            spec = (spec.get("barrios") or {}).get(barrio) or {}
        return spec

    def slugs(self, source: str, city: str, barrio: Optional[str] = None) -> List[str]:
        """How ``source`` names a city or one of its barrios in search URLs."""
        return list((self._spec(city, barrio).get("slugs") or {}).get(source) or [])

    def ids(self, source: str, city: str, barrio: Optional[str] = None) -> List[str]:
        return list((self._spec(city, barrio).get("ids") or {}).get(source) or [])

    def resolve_key(self, key: str) -> Optional[str]:
        """A stored or configured barrio ("CABA/Recoleta", or a bare
        "barrio norte") as its canonical key, or None if unknown."""
        location = split_key(key)
        if location.city not in self.cities_map:
            return None
        found = self.from_label(location.neighborhood, location.city)
        return barrio_key(found.city, found.neighborhood) if found and found.neighborhood else None

    # ------------------------------------------------------------------ resolve

    def city_from_label(self, label: Optional[str]) -> Optional[str]:
        if not label:
            return None
        return self._city_aliases.get(normalize_text(label))

    def from_label(self, label: Optional[str], city: Optional[str] = None) -> Optional[Location]:
        """Resolve a structured location label rendered by the site.

        Only exact alias matches count. A free-text address is deliberately
        NOT accepted here: "Av. Santa Fe 1234, Palermo" must not become
        "Barrio Norte" just because the description mentions the zone. A
        label that names barrios in several cities needs ``city``.
        """
        if not label:
            return None
        found = self._labels.get(normalize_text(label), [])
        if city is not None:
            found = [location for location in found if location.city == city]
        return found[0] if len(found) == 1 else None

    def from_slug(self, source: str, slug: Optional[str]) -> Optional[Location]:
        if not slug:
            return None
        return self._slugs.get(f"{source}|{slug.strip('/')}")

    def from_ids(self, source: str, identifiers: Iterable[Optional[str]]) -> Optional[Location]:
        """The first of a site's internal ids we know - pass the most
        specific first. The strongest signal there is: ArgenProp shows
        "Parque Las Heras" on a card it files under Barrio Norte's id."""
        for identifier in identifiers:
            if identifier is None or str(identifier).strip() == "":
                continue
            location = self._ids.get(f"{source}|{str(identifier).strip()}")
            if location:
                return location
        return None

    def from_id(self, source: str, identifier: Optional[str]) -> Optional[Location]:
        return self.from_ids(source, [identifier])

    def from_location_path(self, source: str, parts: List[str]) -> Optional[Location]:
        """Resolve a site's structured location breadcrumb, such as
        ["Ayacucho 800", "Recoleta", "Capital Federal"].

        The city is the most specific part naming one ("La Plata" before
        "Bs.As. G.B.A. Sur", which would be AMBA); the barrio is the part
        closest to the city that names a barrio of it (closest, because the
        far end is the street, which may share a barrio's name). A part
        naming a barrio of a single city is enough on its own ("Tigre" is in
        AMBA).
        """
        parts = [p for p in parts if p]
        city = next(
            (self.city_from_label(part) for part in parts if self.city_from_label(part)),
            None,
        )
        for part in reversed(parts):
            location = self.from_label(part, city) or self.from_slug(source, part)
            if location and (city is None or location.city == city):
                return location
        return Location(city) if city else None
